/**
 * npm run gen:api — generates the UI's API types from the runtime server's contract vendored in
 * contract/ by npm run sync:contract (lever L12):
 *   - src/lib/api/generated/schema.d.ts from generated/openapi.json (openapi-typescript), once the
 *     server publishes it (task P2-03);
 *   - src/lib/api/generated/models.ts from the server's class-model JSON Schemas
 *     (json-schema-to-typescript), for the models listed in api-models.json and everything they
 *     reference: the error envelope now; events and content parts as the server adds them.
 * npm run gen:api:check — fails when the committed files differ (case U-14).
 *
 * CONTRACT_DIR points at the vendored contract (default: contract/; the drift test uses a copy).
 */
import fs from 'node:fs';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const root = process.cwd();
const contractDir = path.resolve(root, process.env.CONTRACT_DIR ?? 'contract');
const schemasDir = path.join(contractDir, 'schemas');
const openapiFile = path.join(contractDir, 'openapi.json');
const outDir = path.join(root, 'src', 'lib', 'api', 'generated');
const check = process.argv.includes('--check');
const banner = '/* eslint-disable */\n// Generated by scripts/gen-api.mjs from the runtime server contract. Do not edit.\n';

const { models } = JSON.parse(fs.readFileSync(path.join(root, 'api-models.json'), 'utf8'));
if (!fs.existsSync(schemasDir)) {
  console.error(`No vendored schemas at ${schemasDir}; run npm run sync:contract.`);
  process.exit(1);
}

const raw = Object.fromEntries(
  fs
    .readdirSync(schemasDir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => [file.slice(0, -5), JSON.parse(fs.readFileSync(path.join(schemasDir, file), 'utf8'))]),
);
const openapi = fs.existsSync(openapiFile) ? JSON.parse(fs.readFileSync(openapiFile, 'utf8')) : undefined;

// The LangGraph runtime's schemas are Pydantic validation schemas: a field is optional only when it
// has a default (a default_factory shows no default). Its HTTP responses drop only nulls
// (response_model_exclude_none), so in a response model an optional field that cannot be null is
// always present and is typed as required here. Events and content parts can be built as plain
// dicts, so there only the `type` discriminator (a const) is required; their other optional
// fields stay optional. Request bodies keep the schema as it is.
const refsOf = (value) => [...JSON.stringify(value).matchAll(/#\/components\/schemas\/(\w+)/g)].map((m) => m[1]);
const reach = (roots, stop = new Set()) => {
  const found = new Set();
  const walk = (name) => {
    if (found.has(name) || stop.has(name)) return;
    found.add(name);
    refsOf(raw[name] ?? openapi?.components?.schemas?.[name] ?? {}).forEach(walk);
  };
  roots.forEach(walk);
  return found;
};
const operations = Object.values(openapi?.paths ?? {}).flatMap((item) => Object.values(item));
const requestModels = reach([
  'ApprovalAnswer',
  'InputAnswer',
  ...operations.flatMap((operation) => refsOf(operation.requestBody ?? {})),
]);
// POST /v1/runs can answer with the event stream; events are not response models.
const responseModels = reach(
  operations.flatMap((operation) => refsOf(operation.responses ?? {})),
  new Set(['RunEvent']),
);

const requireConst = (schema) => {
  if (Array.isArray(schema)) return schema.map(requireConst);
  if (typeof schema !== 'object' || schema === null) return schema;
  const out = Object.fromEntries(Object.entries(schema).map(([key, value]) => [key, requireConst(value)]));
  if (out.properties?.type?.const !== undefined) out.required = [...new Set([...(out.required ?? []), 'type'])];
  return out;
};
const nullable = (property) =>
  property.default === null ||
  property.type === 'null' ||
  (Array.isArray(property.type) && property.type.includes('null')) ||
  (property.anyOf ?? property.oneOf ?? []).some(nullable);
const requireSent = (schema) => {
  if (Array.isArray(schema)) return schema.map(requireSent);
  if (typeof schema !== 'object' || schema === null) return schema;
  const out = Object.fromEntries(Object.entries(schema).map(([key, value]) => [key, requireSent(value)]));
  if (out.properties && typeof out.properties === 'object' && !Array.isArray(out.properties)) {
    const sent = Object.entries(out.properties)
      .filter(([, property]) => typeof property === 'object' && property !== null && !nullable(property))
      .map(([name]) => name);
    if (sent.length > 0) out.required = [...new Set([...(out.required ?? []), ...sent])];
  }
  return out;
};
const asWire = (name, schema) =>
  requestModels.has(name) ? schema : responseModels.has(name) ? requireSent(schema) : requireConst(schema);

// A Pydantic `Any` field is a schema with only a title (and a default); json-schema-to-typescript
// would make that an object type, so it is typed `unknown` (its tsType; openapi-typescript ignores it).
const SHAPE_KEYS = ['type', '$ref', 'anyOf', 'oneOf', 'allOf', 'enum', 'const', 'properties', 'items'];
const untypedAsUnknown = (schema) => {
  if (Array.isArray(schema)) return schema.map(untypedAsUnknown);
  if (typeof schema !== 'object' || schema === null) return schema;
  const out = Object.fromEntries(Object.entries(schema).map(([key, value]) => [key, untypedAsUnknown(value)]));
  if (out.properties && typeof out.properties === 'object' && !Array.isArray(out.properties))
    for (const [field, property] of Object.entries(out.properties))
      if (typeof property === 'object' && property !== null && !SHAPE_KEYS.some((key) => key in property)) {
        out.properties[field] = { ...property, tsType: 'unknown' };
      }
  return out;
};

const all = Object.fromEntries(
  Object.entries(raw).map(([name, schema]) => [name, untypedAsUnknown(asWire(name, schema))]),
);
if (openapi?.components?.schemas)
  for (const [name, schema] of Object.entries(openapi.components.schemas))
    openapi.components.schemas[name] = untypedAsUnknown(asWire(name, schema));

// The listed models and every model they reference.
const wanted = new Set();
const visit = (name) => {
  if (wanted.has(name)) return;
  if (!all[name]) throw new Error(`api-models.json names ${name}, which contract/ does not hold; run npm run sync:contract`);
  wanted.add(name);
  JSON.stringify(all[name]).replace(/#\/components\/schemas\/(\w+)/g, (_, ref) => (visit(ref), ''));
};
models.forEach(visit);

const definitions = Object.fromEntries(
  [...wanted].sort().map((name) => [name, JSON.parse(JSON.stringify(all[name]).replaceAll('#/components/schemas/', '#/definitions/'))]),
);
const rootSchema = {
  title: 'RuntimeApiModels',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(definitions).map((name) => [name, { $ref: `#/definitions/${name}` }])),
  definitions,
};

const files = new Map();
const modelsTs = await compile(rootSchema, 'RuntimeApiModels', {
  bannerComment: banner,
  declareExternallyReferenced: true,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true, printWidth: 110 },
});
files.set('models.ts', modelsTs);

if (openapi) {
  const ast = await openapiTS(openapi);
  files.set('schema.d.ts', banner + astToString(ast));
} else {
  files.set(
    'schema.d.ts',
    `${banner}// The server publishes generated/openapi.json with the API (task P2-03); until then no paths exist.\nexport type paths = Record<string, never>;\nexport type components = { schemas: Record<string, never> };\n`,
  );
}

let stale = [];
for (const [name, content] of files) {
  const target = path.join(outDir, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : undefined;
  if (current === content) continue;
  if (check) stale.push(name);
  else {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(target, content);
  }
}
if (check && stale.length > 0) {
  console.error(`Generated API types are out of date (run npm run gen:api): ${stale.join(', ')}`);
  process.exit(1);
}
console.log(check ? 'Generated API types are up to date' : `Wrote ${files.size} generated files for ${wanted.size} models`);
